// Generates frontend/src/assets/database/database-2024-<hash>.zip from the committed
// database-2024.json, and writes the zip's served path into the committed
// src/app/generated/database-zip.ts the Angular app imports. The loose JSON is the
// source of truth in git (readable diffs); the zip is a gitignored build derivative
// the app fetches and unpacks with JSZip.
//
// The name carries the first 16 hex chars of the JSON's SHA-256, so the file never
// changes under its name: the origin serves it immutable for a year (see
// staticCacheControl in app/static-controller.ts) and a browser holding an old one
// never shows a new bundle a stale database — the new bundle asks for a new name.
// Before this the zip had one fixed name, Cloudflare's browser TTL held it for four
// hours past a deploy, and every visit after that re-downloaded all of it.
//
// Wired as the frontend `prebuild` + `prestart` so the zip exists before `ng build`
// (prod/CI) and `ng serve` (dev), and run by `npm run import:2024` so the committed
// constant moves with the JSON in the same commit. A backend test
// (database-validation.test.ts) fails when the constant and the JSON disagree. Skips
// the zip when the one for this hash already exists, so repeat runs are instant.
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");
const JSZip = require("jszip");

const dbDir = path.join(__dirname, "..", "src", "assets", "database");
const jsonPath = path.join(dbDir, "database-2024.json");
const generatedPath = path.join(
  __dirname,
  "..",
  "src",
  "app",
  "generated",
  "database-zip.ts",
);

// Shared with the backend test and staticCacheControl: a change here is a change there.
const HASH_HEX_CHARS = 16;

function zipNameFor(jsonBytes) {
  const hash = crypto
    .createHash("sha256")
    .update(jsonBytes)
    .digest("hex")
    .slice(0, HASH_HEX_CHARS);
  return `database-2024-${hash}.zip`;
}

function generatedSource(zipName) {
  return (
    "// Generated by frontend/scripts/build-database-zip.js from the SHA-256 of\n" +
    "// src/assets/database/database-2024.json. Do not edit: run `npm run import:2024`\n" +
    "// (or `npm run build:database-zip` from frontend/) and commit the result with the JSON.\n" +
    `export const DATABASE_ZIP_PATH = "assets/database/${zipName}";\n`
  );
}

function writeIfChanged(file, content) {
  let current = null;
  try {
    current = fs.readFileSync(file, "utf8");
  } catch {}
  if (current === content) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return true;
}

async function main() {
  if (!fs.existsSync(jsonPath)) {
    console.error(
      `[build-database-zip] missing ${path.relative(
        process.cwd(),
        jsonPath,
      )} — ` + "run `npm run import:2024` from the repo root first.",
    );
    process.exit(1);
  }

  const json = fs.readFileSync(jsonPath);
  const zipName = zipNameFor(json);
  const zipPath = path.join(dbDir, zipName);

  if (writeIfChanged(generatedPath, generatedSource(zipName)))
    console.log(
      `[build-database-zip] wrote ${path.relative(process.cwd(), generatedPath)}`,
    );

  // Prune zips for other hashes: only the current one is referenced, and a stale
  // sibling would otherwise ship in every build until someone noticed.
  for (const name of fs.readdirSync(dbDir)) {
    if (/^database-2024(-[0-9a-f]+)?\.zip$/.test(name) && name !== zipName)
      fs.unlinkSync(path.join(dbDir, name));
  }

  if (fs.existsSync(zipPath)) {
    console.log("[build-database-zip] zip up to date, skipping");
    return;
  }

  const zip = new JSZip();
  // Entry MUST be named "database.json": the app reads zipped.files["database.json"].
  // Fixed date keeps the output reproducible (it is gitignored, but tidy regardless).
  zip.file("database.json", json, { date: new Date(0) });
  const buf = await zip.generateAsync({
    type: "nodebuffer",
    compression: "DEFLATE",
    compressionOptions: { level: 9 },
  });
  fs.writeFileSync(zipPath, buf);
  console.log(
    `[build-database-zip] wrote ${path.relative(process.cwd(), zipPath)} (${
      buf.length
    } bytes)`,
  );
}

main().catch((err) => {
  console.error("[build-database-zip] failed:", err);
  process.exit(1);
});
